const standardSizes = [
  { label: "250 g", weightGrams: 250 },
  { label: "500 g", weightGrams: 500 },
  { label: "750 g", weightGrams: 750 },
  { label: "1 kg", weightGrams: 1000 },
];

function createFamilyVariants(
  familySlug: string,
  baseName: string,
  sourceCodePrefix: string
): ProductVariant[] {
  return standardSizes.map((size) => ({
    id: `${familySlug}-${size.label.toLowerCase().replace(/\s+/g, "")}`,
    label: size.label,
    weightGrams: size.weightGrams,
    sourceName: `${baseName} ${size.label}`,
    sourceItemCode: `${sourceCodePrefix}${size.weightGrams === 1000 ? "" : size.weightGrams}`,
    sellingPrice: null, // As required: prices remain unverified in source data
  }));
}

